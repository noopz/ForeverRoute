// Writes addon/ForeverRoute/Breadcrumbs.lua from the quest data: breadcrumb quest -> the quests it leads to. The game
// stops offering a breadcrumb once one of those is in your log or done (Argos Nightwhisper had nothing for a level-26
// gnome with Researching the Corruption in the log), so the addon passes it on any plan. usage: node tools/gen-breadcrumbs.js
const fs = require('fs');
const path = require('path');
const db = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'qdb', 'db.json'), 'utf8'));
const bc = {};
for (const t of Object.values(db.quests)) for (const b of t.breadcrumbs || []) (bc[b] = bc[b] || []).push(t.id);
const keys = Object.keys(bc).map(Number).sort((a, b) => a - b);
const L = ['-- Generated by tools/gen-breadcrumbs.js from the quest data - edit that, not this.', 'local _, ns = ...',
  '-- breadcrumb quest -> the quests it leads to', 'ns.BREADCRUMBS = {', ...keys.map((b) => `  [${b}] = { ${bc[b].join(', ')} },`), '}'];
fs.writeFileSync(path.join(__dirname, '..', 'addon', 'ForeverRoute', 'Breadcrumbs.lua'), L.join('\n') + '\n');
console.log(keys.length + ' breadcrumbs');
