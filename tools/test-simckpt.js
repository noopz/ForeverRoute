// Checks for simckpt.js (the simulated player's checkpoints): a checkpoint's key stays the same when only steps past
// what it depends on change, and changes when anything it depends on does; the store keeps only what matches.
// usage: node tools/test-simckpt.js
const fs = require('fs');
const os = require('os');
const path = require('path');
const CK = require('./simckpt');

let fails = 0;
const check = (name, ok) => { console.log((ok ? 'ok   ' : 'FAIL ') + name); if (!ok) fails++; };

// a plan in the planner's layout: 200 steps over 4 zones (50 each), quest q<j> on step j, quest 9001 held from step 10
// to a hand-in at step 180
const ZONES = ['Elwynn Forest', 'Westfall', 'Duskwood', 'Wetlands'];
function planText(o = {}) {
  const steps = [];
  for (let j = 1; j <= 200; j++) {
    const z = Math.floor((j - 1) / 50);
    let s = `{ k = "accept", npc = "N${j}", r = 6, q = ${1000 + j}, name = "Q${j}", level = 1, m = ${1429 + z}, x = 0.5, y = 0.5, zone = "${ZONES[z]}", sec = ${z + 1}, lvl = ${1 + z}, id = ${j} }`;
    if (j === 10) s = `{ k = "accept", npc = "Held", r = 6, q = 9001, name = "Held", level = 1, m = 1429, x = 0.4, y = 0.4, zone = "Elwynn Forest", sec = 1, lvl = 1, id = ${j} }`;
    if (j === 180) s = `{ k = "turnin", npc = "Held", r = 6, q = 9001, name = "Held", level = 1, m = 1432, x = 0.4, y = 0.4, zone = "Wetlands", sec = 4, lvl = 4, id = ${j} }`;
    if (o.step && o.step[j]) s = o.step[j](s);
    steps.push('      ' + s + ',');
  }
  if (o.insert) steps.splice(o.insert - 1, 0, `      { k = "goto", text = "new", m = 1432, x = 0.1, y = 0.1, zone = "Wetlands", sec = 4, id = 0 },`);
  return [
    '-- Built-in plan for a test (tools/starter.js)',
    `-- plans ${o.stamp || '2026-11-11'} · planner abc`,
    'ForeverRouteStarter = ForeverRouteStarter or {}',
    'ForeverRouteStarterStamp = ForeverRouteStarterStamp or {}',
    `ForeverRouteStarterStamp["human-warrior"] = "plans ${o.stamp || '2026-11-11'} · planner abc"`,
    'ForeverRouteStarter["human-warrior"] = function()',
    `-- Generated by the Forever Route path planner on ${o.stamp || '2026-11-11'}. Regenerate rather than edit.`,
    `ForeverRoutePlan = { generated = ${o.gen || 1794439431}, fromSave = 0, zones = { { name = "Elwynn Forest", xph = 1 } }, level = 1, later = { ${o.later || '"Westfall"'} } }`,
    'ForeverRouteRoutes = {',
    '  {',
    `    id = "path:${o.pathId || 'ElwynnForest-Westfall'}",`,
    `    title = "${o.title || 'Elwynn Forest'}",`,
    `    meta = { character = "Starter", hours = ${o.hours || 100}, legs = "Elwynn Forest > Westfall" },`,
    '    sections = {',
    ...ZONES.map((z) => `      { title = "${z}: hub", zone = "${z}" },`),
    '    },',
    '    steps = {',
    ...steps,
    '    },',
    '  },',
    '  {',
    '    id = "special:Bag",',
    `    meta = { hours = ${o.hours || 100} },`,
    `    quests = "${o.special || 'a, b'}",`,
    '    packed = [==[',
    '      { k = "accept", q = 77, id = 1 },',
    ']==],',
    '  },',
    '}',
    'ForeverRouteEnders = {',
    '  [9001] = { npc = "Held", m = 1432, x = 0.4, y = 0.4, name = "Held" },',
    `  [1150] = { npc = "${o.ender150 || 'N150'}", m = 1431, x = 0.5, y = 0.5, name = "Q150" },`,
    '}',
    'ForeverRouteUnlocks = {',
    `  [1005] = { ${o.unlock5 || '1006'} },`,
    '  [1170] = { 1171 },',
    '}',
    '',
    'end',
  ].join('\r\n');
}

const plan = CK.parsePlan(planText());
check('the plan parses: 200 steps, 4 sections', plan.steps.length === 200 && plan.sections.length === 4);
check('steps read: kind, quest, section', plan.steps[9].q === 9001 && plan.steps[179].k === 'turnin' && plan.steps[60].sec === '2');
check('the other route is kept without its meta line', plan.others.some((l) => l.includes('special:Bag')) && !plan.others.some((l) => /meta =/.test(l)));
check('enders and unlocks read', plan.enders.size === 2 && plan.unlocks.length === 2);
const B = CK.legs(plan);
check('legs: where the zone changes, 40+ steps apart (51, 101, 151)', JSON.stringify(B) === '[51,101,151]');
check('legs: a minimum longer than a zone merges them', JSON.stringify(CK.legs(plan, 60)) === '[101]');

const base = CK.baseOf('code', { combo: 'human-warrior', race: 'Human', cls: 'Warrior', persona: 'clean', seed: 1 });
// a checkpoint after leg 1: reached step 60, hi = 60 + 120 = 180 would include the hand-in; take hi = 120
const meta = { v: 1, leg: 1, B: 51, hi: 120, quests: [9001, 1050], nsteps: 200 };
const k0 = CK.keyOf(plan, meta, base);
const keyWith = (o, m = meta, b = base) => CK.keyOf(CK.parsePlan(planText(o)), m, b);
check('a key is 20 hex characters and repeatable', /^[0-9a-f]{20}$/.test(k0) && keyWith({}) === k0);
check('the stamp, generated time, zones-later list, title and route meta do not count',
  keyWith({ stamp: '2027-01-01', gen: 1, later: '"Duskwood", "Wetlands"', title: 'Other', hours: 5, pathId: 'Elwynn-Other' }) === k0);
check('a step past hi changes nothing', keyWith({ step: { 150: (s) => s.replace('N150', 'Someone') } }) === k0);
check('a step inserted past hi changes nothing', keyWith({ insert: 160 }) === k0);
check('an id renumbered changes nothing', keyWith({ step: { 30: (s) => s.replace('id = 30', 'id = 31') } }) === k0);
check('a step at or before hi changes the key', keyWith({ step: { 120: (s) => s.replace('N120', 'X') } }) !== k0);
check('a step in the first leg changes the key', keyWith({ step: { 3: (s) => s.replace('x = 0.5', 'x = 0.6') } }) !== k0);
check('a step inserted before hi changes the key', keyWith({ insert: 100 }) !== k0);
check('the hand-in of a held quest, far past hi, changes the key', keyWith({ step: { 180: (s) => s.replace('x = 0.4', 'x = 0.45') } }) !== k0);
check('...but not for a checkpoint that does not hold it', keyWith({ step: { 180: (s) => s.replace('x = 0.4', 'x = 0.45') } }, { ...meta, quests: [1050] }) === CK.keyOf(plan, { ...meta, quests: [1050] }, base));
check('the hand-in spot of a held quest counts, of another not', keyWith({ ender150: 'Y' }, { ...meta, quests: [1150] }) !== CK.keyOf(plan, { ...meta, quests: [1150] }, base) && keyWith({ ender150: 'Y' }) === k0);
check('an unlock of a quest within hi counts', keyWith({ unlock5: '1006, 1007' }) !== k0);
check('a side route changing changes the key', keyWith({ special: 'a, b, c' }) !== k0);
check('another persona, seed or code: another key', CK.keyOf(plan, meta, CK.baseOf('code', { combo: 'human-warrior', race: 'Human', cls: 'Warrior', persona: 'skip', seed: 1 })) !== k0
  && CK.keyOf(plan, meta, CK.baseOf('code', { combo: 'human-warrior', race: 'Human', cls: 'Warrior', persona: 'clean', seed: 2 })) !== k0
  && CK.keyOf(plan, meta, CK.baseOf('code2', { combo: 'human-warrior', race: 'Human', cls: 'Warrior', persona: 'clean', seed: 1 })) !== k0);
check('a bind step past hi counts', keyWith({ step: { 170: () => '{ k = "bind", bind = "Inn", m = 1432, x = 0.2, y = 0.2, zone = "Wetlands", sec = 4, id = 170 }' } }) !== k0);
check('hi at the plan\'s end: the plan growing changes the key', (() => {
  const m = { ...meta, hi: 200 };
  return CK.keyOf(plan, m, base) !== keyWith({ insert: 201 }, m);
})());
check('a checkpoint past the plan\'s end has no key', CK.keyOf(plan, { ...meta, hi: 500 }, base) === null);

// the store: written checkpoints go in under their key; the deepest matching one is picked; the rest are dropped
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'fr-ckpt-test-'));
const stage = path.join(tmp, 'stage'), store = path.join(tmp, 'store');
fs.mkdirSync(stage);
const write = (f, m, complete = true) => fs.writeFileSync(path.join(stage, f), '-- META ' + JSON.stringify(m) + '\nlocal T = {}\nreturn T\n' + (complete ? '-- end\n' : ''));
write('001.lua', meta);
write('002.lua', { ...meta, leg: 2, B: 101, hi: 170 });
write('003.lua', { ...meta, leg: 3, B: 151, hi: 200 }, false); // the run was stopped while writing it
write('004.lua', { ...meta, leg: 4, unsafe: 'x (function)' });
const r1 = CK.ingest(stage, plan, base, store);
check('ingest: complete ones stored, the unfinished one not, the unsafe one reported', r1.added === 2 && r1.kept === 2 && r1.unusable.length === 1);
check('readMeta rejects an incomplete file', CK.readMeta(path.join(stage, '003.lua')) === null && CK.readMeta(path.join(stage, '001.lua')).leg === 1);
let got = CK.pick(plan, base, store);
check('pick: the deepest matching checkpoint (leg 2)', got.file && got.meta.leg === 2 && got.of === 2);
const late = CK.parsePlan(planText({ step: { 150: (s) => s.replace('N150', 'Someone') } }));
got = CK.pick(late, base, store);
check('a step changed in leg 3 (within leg 2\'s hi): resumes from leg 1', got.file && got.meta.leg === 1);
const early = CK.parsePlan(planText({ step: { 5: (s) => s.replace('N5', 'Someone') } }));
check('a step changed in leg 1: nothing matches', CK.pick(early, base, store).file === null);
fs.rmSync(stage, { recursive: true }); fs.mkdirSync(stage);
const r2 = CK.ingest(stage, late, base, store);
check('after a run on the changed plan the store keeps only what matches it', r2.kept === 1 && r2.dropped === 1 && CK.pick(late, base, store).meta.leg === 1);
fs.rmSync(tmp, { recursive: true, force: true });

// the real built-in plans parse, and every leg has steps
const addon = path.join(__dirname, '..', 'addon');
let n = 0, bad = [];
for (const d of fs.readdirSync(addon).filter((x) => x.startsWith('ForeverRoute_Starter_'))) {
  try { const p = CK.parsePlan(fs.readFileSync(path.join(addon, d, 'Plan.lua'), 'utf8')); if (CK.legs(p).length < 10) bad.push(d + ' (few legs)'); n++; } catch (e) { bad.push(d + ': ' + e.message); }
}
check(`the built-in plans parse (${n})`, n > 0 && !bad.length);
if (bad.length) console.log(bad.join('\n'));

console.log(fails ? fails + ' FAILED' : 'all passed');
process.exitCode = fails ? 1 : 0;
