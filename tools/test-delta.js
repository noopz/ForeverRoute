// A QuestieDB update re-plans only the legs whose data changed (tools/datasig.js keys the leg cache) - and must give the
// same plan as planning from scratch. This plans a short character, changes one quest the plan does halfway (its XP
// doubled), then plans again both ways and compares.
// usage: node tools/test-delta.js [race=gnome] [class=warlock] [target=20]
const fs = require('fs');
const path = require('path');
const os = require('os');
const { execFileSync } = require('child_process');
const RF = require('./routefile');
const ROOT = path.join(__dirname, '..');
const [race = 'gnome', cls = 'warlock', target = '20'] = process.argv.slice(2);
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'fr-delta-'));
const plan = (name, extra) => {
  const t0 = Date.now();
  execFileSync(process.execPath, [path.join(__dirname, 'starter.js'), race, cls, target], { cwd: ROOT, env: { ...process.env, FR_EXPERIMENT: name, FR_EXTRA: JSON.stringify(extra) }, stdio: 'ignore', timeout: 30 * 60000 });
  const dir = path.join(ROOT, 'paths-starter', `${race}-${cls}-${name}`);
  const text = fs.readFileSync(path.join(dir, 'Route.lua'), 'utf8').split('\n').filter((l) => !/Generated by|generated = /.test(l)).join('\n');
  const runs = /planner runs: (\d+) reused from earlier plans, (\d+) planned fresh/.exec(fs.readFileSync(path.join(dir, 'path-0.log'), 'utf8')) || [];
  return { text, dir, reused: +runs[1], fresh: +runs[2], sec: Math.round((Date.now() - t0) / 1000) };
};
const fail = (m) => { console.log('FAIL ' + m); process.exitCode = 1; };
// 1. the plan on today's data (fills the cache)
const A = plan('delta-a', { exactCache: true });
// 2. one quest the plan does halfway: XP doubled, in a copy of the data
const steps = RF.steps(A.text, RF.routeIds(A.text).find((x) => /^path:/.test(x)));
const turnins = steps.filter((s) => s.k === 'turnin' && s.q > 0);
const q = turnins[Math.floor(turnins.length / 2)].q;
const db = JSON.parse(fs.readFileSync(path.join(ROOT, 'qdb', 'db.json'), 'utf8'));
const before = db.quests[q].xp; db.quests[q].xp = (before || 500) * 2;
const dbB = path.join(tmp, 'db.json'); fs.writeFileSync(dbB, JSON.stringify(db));
console.log(`changed quest ${q} ${db.quests[q].name} [${db.quests[q].level}]: xp ${before} -> ${db.quests[q].xp}`);
// 3. again, both ways
const inc = plan('delta-inc', { db: dbB, exactCache: true });
const full = plan('delta-full', { db: dbB, noCache: true, exactCache: true });
console.log(`full plan on today's data: ${A.sec}s (${A.fresh} legs planned)`);
console.log(`after the change - delta: ${inc.sec}s, ${inc.fresh} legs re-planned, ${inc.reused} reused; from scratch: ${full.sec}s, ${full.fresh} legs`);
if (inc.text !== full.text) fail('the delta plan differs from the plan made from scratch');
else console.log('ok   the delta plan is the same as the plan made from scratch');
if (!(inc.reused > 0)) fail('the delta reused nothing');
if (inc.text === A.text) console.log('note the change did not alter the plan (the XP moved no decision)');
fs.rmSync(tmp, { recursive: true, force: true });
if (!process.exitCode) for (const n of ['delta-a', 'delta-inc', 'delta-full']) fs.rmSync(path.join(ROOT, 'paths-starter', `${race}-${cls}-${n}`), { recursive: true, force: true });
if (!process.exitCode) console.log('all passed');
