// Quest-reward items that might be fun (toys, transforms, pets, gadgets): the non-gear rewards of quests up to level
// 45 - miscellaneous items, consumables, trinkets and rings. The quest data says which quests give them, not what they
// do; the addon asks the game (Learn.lua: is it a toy, what does its "Use:" say) and the companion makes the fun ones
// worth a detour. Writes addon/ForeverRoute/FunCandidates.lua. Run after rebuilding qdb.
// usage: node tools/fun-candidates.js
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const items = JSON.parse(fs.readFileSync(path.join(ROOT, 'qdb', 'json', 'items.json'), 'utf8'));
const db = JSON.parse(fs.readFileSync(path.join(ROOT, 'qdb', 'db.json'), 'utf8'));
const out = [];
for (const [id, v] of Object.entries(items)) {
  const qs = v['6']; if (!qs) continue;
  const quests = (Array.isArray(qs) ? qs : Object.values(qs)).filter((q) => db.quests[q] && (db.quests[q].level || 60) <= 45);
  if (!quests.length) continue;
  const cls = v['12'] || 0, sub = v['13'] || 0; // item class / subclass (0 is left out of the data)
  if (!(cls === 15 || cls === 0 || (cls === 4 && sub === 0))) continue; // misc, consumable, misc armor (trinkets, rings...)
  out.push(`  [${id}] = { ${quests.join(', ')} }, -- ${String(v['1']).replace(/\n/g, ' ')}`);
}
const L = ['-- Generated by tools/fun-candidates.js: quest-reward items that might be fun (item -> the quests that give it).',
  '-- Learn.lua asks the game which of them are toys or transforms.', 'local _, ns = ...', 'ns.FUN_CANDIDATES = {', ...out, '}'];
fs.writeFileSync(path.join(ROOT, 'addon', 'ForeverRoute', 'FunCandidates.lua'), L.join('\n') + '\n');
console.log(out.length + ' candidate items');
