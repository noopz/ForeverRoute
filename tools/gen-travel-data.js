// Writes addon/ForeverRoute/TravelData.lua from tools/travel-facts.json, so the addon and the planner (tools/travel.js)
// route over the same facts. usage: node gen-travel-data.js   (run after editing travel-facts.json)
const fs = require('fs');
const path = require('path');
const facts = JSON.parse(fs.readFileSync(path.join(__dirname, 'travel-facts.json'), 'utf8'));
const lua = (v, ind) => {
  if (v === null || v === undefined) return 'nil';
  if (typeof v === 'string') return JSON.stringify(v);
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  if (Array.isArray(v)) return '{ ' + v.map((x) => lua(x, ind)).join(', ') + ' }';
  const keys = Object.keys(v);
  const key = (k) => (/^\d+$/.test(k) ? '[' + k + ']' : /^[A-Za-z_]\w*$/.test(k) ? k : '[' + JSON.stringify(k) + ']');
  const flat = keys.every((k) => typeof v[k] !== 'object' || v[k] === null);
  if (flat) return '{ ' + keys.map((k) => key(k) + ' = ' + lua(v[k], ind)).join(', ') + ' }';
  return '{\n' + keys.map((k) => ind + '  ' + key(k) + ' = ' + lua(v[k], ind + '  ') + ',').join('\n') + '\n' + ind + '}';
};
const L = ['-- Generated by tools/gen-travel-data.js from tools/travel-facts.json - edit that file, not this one.', 'local _, ns = ...', 'ns.TravelData = {'];
for (const [k, v] of Object.entries(facts)) { if (k.startsWith('_')) continue; L.push('  ' + k + ' = ' + lua(v, '  ') + ','); }
// the other faction's towns and camps (tools/hostile-towns.json): rides through them cost HOSTILE_SEC more
{ let H = {}; try { H = JSON.parse(fs.readFileSync(path.join(__dirname, 'hostile-towns.json'), 'utf8')); } catch (e) {}
  L.push('  HOSTILE = {');
  for (const side of ['alliance', 'horde']) { L.push('    ' + side + ' = {'); for (const h of H[side] || []) L.push('      { m = ' + h.m + ', x = ' + h.x + ', y = ' + h.y + ', r = ' + h.r + ', name = ' + JSON.stringify(h.name) + ' },'); L.push('    },'); }
  L.push('  },'); }
// the ride network from the walk maps (tools/crossings.js): nodes { id, kind, m, x, y, name, dock, m2, x2, y2 } and
// edges { a, b, zone, yd } as compact arrays
const netFile = path.join(__dirname, 'travel-net.json');
if (fs.existsSync(netFile)) {
  const net = require('./net').load(facts);
  L.push('  NET = {', '    nodes = {');
  for (const n of net.nodes) L.push('      ' + lua({ id: n.id, kind: n.kind, m: n.m, x: n.x, y: n.y, name: n.name, dock: n.dock, m2: n.m2, x2: n.x2, y2: n.y2 }) + ',');
  L.push('    },', '    edges = {');
  for (let i = 0; i < net.edges.length; i += 6) L.push('      ' + net.edges.slice(i, i + 6).map((e) => '{ ' + JSON.stringify(e.a) + ', ' + JSON.stringify(e.b) + ', ' + e.zone + ', ' + e.yd + ' }').join(', ') + ',');
  L.push('    },', '  },');
  // zone bounds of every map the network uses (world yards: left/right/top/bottom, continent) - only the tests read
  // them (the sim has no map data); the addon itself goes through HereBeDragons
  const conv = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'qdb', 'conversion.json'), 'utf8')).geometry.transforms;
  const used = new Set(net.nodes.flatMap((n) => [n.m, n.m2]).filter(Boolean));
  for (const d of Object.values(facts.DOCKS)) used.add(d.m);
  for (const k of Object.keys(facts.ZONE_MIN)) used.add(+k);
  L.push('  BOUNDS = {');
  for (const t of conv) { const b = t.target_bounds || t.source_bounds; if (b && used.has(t.ui_map_id)) L.push(`    [${t.ui_map_id}] = { ${b.left.toFixed(1)}, ${b.right.toFixed(1)}, ${b.top.toFixed(1)}, ${b.bottom.toFixed(1)}, ${t.map_id} },`); }
  L.push('  },');
}
L.push('}');
const out =path.join(__dirname, '..', 'addon', 'ForeverRoute', 'TravelData.lua');
fs.writeFileSync(out, L.join('\n') + '\n');
console.log('wrote ' + out);
